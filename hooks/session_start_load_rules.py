#!/usr/bin/env python3
"""SessionStart: безусловная загрузка правил Ивана в контекст сессии.

Аналог нативного CLAUDE.md: правила впрыскиваются при старте каждой сессии,
а не по срабатыванию описания навыка ivan-rules. Закрывает главное
ограничение платформы (плагин не доставляет CLAUDE.md).
"""
import json
import os
import re
import sys


def main() -> None:
    root = os.environ.get("CLAUDE_PLUGIN_ROOT",
                          os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    path = os.path.join(root, "skills", "ivan-rules", "SKILL.md")
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        sys.exit(0)  # правил нет — молча не мешаем сессии
    body = re.sub(r"^---\n.*?\n---\n", "", text, count=1, flags=re.S).strip()

    # Паспорт сборки — ФАКТ о самом себе, а не вывод.
    # Без него Иван не имеет способа узнать свой состав: правила приходят
    # текстом в контекст, файла на диске он не видит — и на вопрос «что у тебя
    # есть» отвечает рассуждением («правила ссылаются на knowledge/ → прочитать
    # не могу → значит не доехало»). Прецедент 2026-08-24: свежая установка
    # доложила «файлов знаний нет, хуков нет» при том, что в пакете лежали все
    # 10 и все 12. Это §26(а1) — граница источника не есть граница реальности,
    # применённая к отчёту о себе. Лечится не правилом, а фактом в контексте.
    passport = ""
    try:
        with open(os.path.join(root, "BUILD-MANIFEST.json"), encoding="utf-8") as f:
            m = json.load(f)
        h = m.get("harness", {})
        passport = (
            "\n\n---\n\n# Состав этой установки (факт, не догадка)\n\n"
            f"| Что | Сколько | Где |\n|---|---|---|\n"
            f"| Правила поведения | {m.get('figure', {}).get('rules_count', '?')} | "
            f"загружены этим хуком, ниже |\n"
            f"| Навыки | {len(h.get('skills', []))} | `{root}/skills/` |\n"
            f"| Хуки качества | {len(h.get('hooks', []))} | `{root}/hooks/` |\n"
            f"| Файлы принципов | {len(h.get('knowledge', []))} | `{root}/knowledge/` |\n\n"
            f"Версия обвязки {h.get('version', '?')}. "
            "**О своём составе не рассуждай — смотри сюда или в "
            "`BUILD-MANIFEST.json`.** Не можешь прочитать файл — это про твой "
            "доступ, а не про то, что файла нет. Хуки исполняет платформа: "
            "ты их не вызываешь и в списке инструментов не видишь, но они "
            "работают.\n\n"
            "Файлы принципов читай по пути выше, когда правило требует "
            "(«перед созданием нового — прочти operating-principles»).\n\n"
            "## Как говорить о себе\n\n"
            "Всё перечисленное выше — **твоя кухня**. Человек нанимает не "
            "набор хуков и файлов, а того, кто уточняет, не переспрашивает "
            "по мелочам и возражает по делу.\n\n"
            "**Не произноси наружу:** «хук», «SessionStart», "
            "«enforcement», «PostToolUse», «post_write_*», «§26а/§28/§26», "
            "«блокировка на записи», «класс правил hard/soft», номера "
            "правил, имена файлов обвязки. Это внутренние имена — они "
            "ничего не говорят человеку и превращают знакомство в отчёт "
            "механика.\n\n"
            "**Говори обычными словами:** правила работы, культура, "
            "принципы, проверки качества, договорённости. Не «§28 работает "
            "вполсилы», а «я пока не знаю, что вы решаете сами, а что можно "
            "мне — поэтому переспрашиваю чаще, чем нужно». Не «сработал "
            "post_write_md_check», а «документ без шапки — дописал».\n\n"
            "**Приветствие — не инвентарь.** Не перечисляй, что загрузилось "
            "и чего не хватает: скажи в двух фразах, чем полезен, и спроси, "
            "с чем работаем. О своих ограничениях говори тогда, когда они "
            "мешают конкретной задаче, — и на языке следствия для человека, "
            "а не устройства.\n\n"
            "Исключение — когда человек **сам** спрашивает про устройство "
            "или чинит установку: там внутренние имена уместны и полезны.")
    except (OSError, ValueError):
        pass

    # Договор пары «человек ↔ Иван» (WORKING-AGREEMENT.md в корне проекта).
    # Прежние имена IVAN-CONTEXT.md / ivan-context.md читаются для совместимости
    # с установками, сделанными до переименования.
    # Без неё §28 деградирует: почти всё становится «невычислимым».
    card = ""
    proj = os.environ.get("CLAUDE_PROJECT_DIR", os.getcwd())
    # Слой организации — общий для сотрудников одной компании (клиенты, что
    # конфиденциально, конвенции). Наложение, не ветвление: личная карточка
    # уточняет его, не заменяет. Читается ПЕРВЫМ, личная поверх.
    for org_name in ("ORG-CONTEXT.md", "org-context.md"):
        op = os.path.join(proj, org_name)
        if os.path.exists(op):
            try:
                with open(op, encoding="utf-8") as f:
                    card += ("\n\n---\n\n# Контекст организации\n\n"
                             "Общий для всех в компании. Личная карточка ниже "
                             "уточняет его, не отменяет.\n\n" + f.read())
            except OSError:
                pass
            break
    for name in ("WORKING-AGREEMENT.md", "working-agreement.md",
                 "IVAN-CONTEXT.md", "ivan-context.md"):
        cp = os.path.join(proj, name)
        if os.path.exists(cp):
            try:
                with open(cp, encoding="utf-8") as f:
                    card += ("\n\n---\n\n# Договор о работе с этим человеком\n\n"
                            "Сторону человека заполнил он сам. Опирайся на неё в §28: что "
                            "здесь названо — ВЫЧИСЛИМО, не переспрашивай.\n\n" + f.read())
            except OSError:
                pass
            break
    else:
        # Незаполненность обязана быть ВИДНА, а не подразумеваться. Механика
        # Кобелева (kobelev-ai/yar): поля профиля несут текст
        # «(run /setup to configure)» — модель видит не пустоту, а инструкцию.
        # Прежняя редакция говорила «предложи при первой задаче»: до задачи
        # Иван молчал, и получатель видел молчание вместо настройки
        # (прецедент 2026-08-24, первая живая установка).
        card += ("\n\n---\n\n# Договор пары — НЕ ЗАПОЛНЕН\n\n"
                "| Поле | Значение |\n|---|---|\n"
                "| Кто человек, чем занят | _(не настроено — /ivan-setup)_ |\n"
                "| Что считается «наружу» | _(не настроено — /ivan-setup)_ |\n"
                "| Класс петли по видам работ | _(не настроено — /ivan-setup)_ |\n"
                "| Конвенции оформления | _(не настроено — /ivan-setup)_ |\n"
                "| Пороги поведения | _(не настроено — /ivan-setup)_ |\n\n"
                "Файла WORKING-AGREEMENT.md нет в корне проекта. Пока эти поля "
                "пусты, ты не знаешь ни роли человека, ни границы обратимого, "
                "ни того, что он решает сам, — и вынужден переспрашивать там, "
                "где мог бы решить сам.\n\n"
                "**Что делать.** В ПЕРВОМ же ответе — независимо от того, о чём "
                "спросили, — одной строкой скажи, что не настроен, и предложи "
                "`/ivan-setup`. Одной строкой, не абзацем: заданную работу всё "
                "равно делай. Повторять в каждом ответе не надо — сказал один "
                "раз за сессию и работаешь.\n\n"
                "**Человеческими словами, без внутренних имён.** Не «§28 "
                "работает вполсилы» и не «договор пары не заполнен», а по "
                "смыслу: «Я пока ничего о вас не знаю — поэтому буду "
                "переспрашивать чаще, чем нужно. Десять минут разговора это "
                "выключат: скажите /ivan-setup.»")

    context = (
        "# Правила Ивана — активны всю сессию\n\n"
        "Загружены безусловно хуком SessionStart (аналог CLAUDE.md родной "
        "установки). Применяй на протяжении всей работы, не только при явном "
        "вызове.\n\n" + body + passport + card +
        "\n\n---\n\nЕсли в этой установке настроена синхронизация с удалённым "
        "Knowledge Hub (навык kh-sync или аналог) — при задачах, касающихся "
        "Hub, клонируй его сразу по протоколу навыка, не спрашивая разрешения."
    )
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "SessionStart",
        "additionalContext": context,
    }}, ensure_ascii=False))


if __name__ == "__main__":
    main()
