#!/usr/bin/env python3
"""Stop hook: ловит ход, закрытый передачей развилки оператору.

Правило 28 (светофор автономности) корректно и полно: ось 1 отвечает про
вычислимое, ось 2 — про обратимость (two-door → делаю сам). Промах — не в
содержании правила, а в том, что воронка не вызывается: чтобы заметить точку
активации «перед каждым вопросом оператору», надо уже осознать, что задаёшь
вопрос. Круг. Хук разрывает круг снаружи — показывает факт «последний абзац
передаёт ход» и требует прогона осей.

Хук НЕ решает, законен вопрос или нет: различить `in` (авторство нормы,
приоритет, замысел — спросить верно) от Василия (вычислимое и обратимое —
надо было делать) машинно нельзя. Поэтому реакция — предупреждение, не блок.

Эмпирика (11 сессий из 12 с Василием формы 1, .claude/logs/autonomy-errors-log.md):
§28 гналась за грамматикой вопроса и достраивала перечень форм после каждого
рецидива («или…?» → «хочешь…?/предлагаю…?» → глагол будущего). Формы вежливого
вопроса неисчерпаемы; ловим не форму, а позицию — передачу хода в конце ответа.

Дополнение 2026-08-17: перечень пропускал ЦЕЛЫЙ КЛАСС — существительное
состояния («ждёт очереди», «исполнима без вас», «ничего не нужно»). Это тот же
ход, замаскированный сильнее: грамматически отчёт, структурно передача.

СМЕНА ПОДХОДА 2026-09-02. Три дополнения перечня подряд (17.08, 02.09 дважды)
— и каждый раз новая форма проходила мимо: «ждёт вашего слова» при пойманном
«ждёт очереди», «Что берём?» при пойманном «Что делаем?». Проверка на формах,
сочинённых за минуту, дала 11 промахов из 13. Вывод: перечень догоняет язык и
всегда отстаёт на одну формулировку — то самое, о чём предупреждает абзац выше
и о чём говорит §28 («возведение признака в правило = подмена сути прокси»).
Хук был написан против погони за грамматикой и сам ею занимался.

Теперь два слоя. Перечень — быстрый и ДЕТЕРМИНИРОВАННЫЙ, ловит очевидное за
0 секунд, батарея §24 остаётся его оракулом. Когда он молчит, а в хвосте нет
следов сделанного, спрашиваем СУДЬЮ (модель): «передаёт ход или отчитывается».
Предикат судьи — предмет, а не признак, поэтому новые формы не требуют правки
кода.

Цена названа прямо: вердикт судьи не воспроизводится в точности, батарея для
второго слоя оракулом не является; пауза до 8 секунд там, где предфильтр не
отсёк; без внешнего `claude` работает только перечень. Замер путей —
0.0с / 0.0с / 6–8с.

Батарея §24 — tests/test_closing_handoff.py (23 ловит / 12 молчит).
"""

import json
import re
import shutil
import subprocess
import sys

import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _transcript_io import load_messages  # noqa: E402

# Передача хода оператору в закрывающей позиции. Широкий невод — точность
# обеспечивает не список, а хвостовая позиция (см. TAIL_CHARS) и warning-режим.
HANDOFF_PATTERNS = [
    r"скажите,?\s+(если|нужно|коммит|делать|стоит|какой|что|куда|заводить)",
    r"скажите\s*—\s*",
    r"\bделать\?",
    r"\bделаем\?",
    r"\bзаводить\?",
    r"\bкоммитить\?",
    r"\bпродолжать\?",
    r"\bпереписать\?",
    r"\bзапускать\?",
    r"\bпрогнать\?",
    r"\bфиксировать\?",
    r"\bзаписывать\?",
    r"\bправить\?",
    r"хотите,?\s+(я|чтобы|сделаю|соберу|прогоню)",
    r"\bхочешь,?\s+(я|чтобы|сделаю|соберу|прогоню)",
    r"предлагаю\s+\w+[.?]?\s*$",
    r"это\s+ваше\s+решение",
    r"это\s+тво[её]\s+решение",
    r"решение\s+за\s+(вами|тобой)",
    r"ваш[ье]?\s+слово",
    r"жду\s+(вашего\s+)?(слова|ответа|решения)",
    r"дайте\s+знать",
    r"как\s+скажете",
    r"на\s+ваше\s+усмотрение",
    r"если\s+скажете\s*[—,-]",
    r"скажете\s+—\s+(сделаю|соберу|прогоню|разложу|заведу)",
    # «— скажите» / «— скажи» в любой обвязке: самая частая мягкая форма,
    # грамматически не вопрос (промах 18.08 «если scope должен остаться уже — скажите»)
    r"[—,-]\s*скаж(ите|и)\b",
    r"\bскаж(ите|и),\s",
    # решение объявлено чужим без вопросительного знака (промах 19.08
    # «Это правка постановки — ваше решение, не моё»)
    r"—\s*ваш[ае]?\s+решение",
    r"—\s*тво[её]\s+решение",
    r"решение,?\s+не\s+мо[её]",
    # инфинитив с «?» в хвосте: «Переписать?», «Заводить задачи?», «Разложить?»
    r"^[А-ЯЁ][а-яё]+(ать|ить|еть|ыть|очь)\b[^.!?\n]{0,60}\?\s*$",
    # КОРОТКИЙ вопрос отдельной строкой в хвосте — передача хода
    # независимо от глагола. Образец выше требовал инфинитива, и мимо
    # проходили «Что берём?», «Что дальше?», «С чего начнём?»,
    # «Куда класть?» — при том что «Что делаем?» ловилось отдельной
    # строкой перечня. Опять перечень вместо позиции.
    #
    # Найдено 2026-09-02 прогоном на РЕАЛЬНЫХ хвостах своих ответов:
    # придуманные случаи эту дыру не показали — они подтверждали ту же
    # правку, из которой выведены. Ограничение длины (до 40 знаков)
    # и одиночная строка отделяют вопрос-передачу от вопроса внутри
    # рассуждения, который законен и ловиться не должен.
    r"^[^.!?\n]{2,40}\?\s*$",
    # СУЩЕСТВИТЕЛЬНОЕ/ПРИЛАГАТЕЛЬНОЕ СОСТОЯНИЯ (промахи 12.08 и 17.08).
    # Тот же ход, замаскированный сильнее прежних: не «сделаю X» и не «X?»,
    # а «X ждёт очереди» / «исполнима без вас» — грамматически отчёт о
    # состоянии, структурно передача хода (работа названа готовой к взятию,
    # взятие оставлено оператору). Прежний перечень ловил вопросы и глаголы
    # будущего и пропускал эту форму целиком: 8 из 11 кейсов батареи.
    # Ключ различения с ЧЕСТНЫМ отчётом («тесты зелёные», «задача закрыта») —
    # честный отчёт говорит о СВЕРШИВШЕМСЯ, эти формы о ПРЕДСТОЯЩЕМ,
    # адресованном оператору. Поэтому привязка к «ждёт / остаётся / готова
    # к / без вас», а не к состоянию вообще.
    r"жд[её]т\s+(только\s+)?(очереди|груминга|своей\s+очереди|взятия|исполнения)",
    # Ожидание, адресованное ОПЕРАТОРУ. Прежняя редакция перечисляла,
    # ЧЕГО ждём (очереди, груминга, взятия) — и пропускала формы, где
    # назван сам оператор: «ждёт вашего слова», «ждёт подтверждения»,
    # «работа ждёт вас». Они передают ход СИЛЬНЕЕ перечисленных, прямо
    # называя, кого ждут. Тот же дефект, который docstring объявляет
    # побеждённым: погоня за перечнем вместо позиции. Курьёз замера
    # 2026-09-02: «Жду вашего слова» ловилось, «Ждёт вашего слова» — нет,
    # разница в одной букве при одном и том же ходе.
    r"жд[её]т\s+(ваше(го|й)?|вас\b|подтверждени|решени|слова|отмашки)",
    r"\bост(а[её]тся|анется)\s+за\s+вами\b",
    r"мяч\s+на\s+вашей\s+стороне",
    r"когда\s+скажете\s*[.!]?\s*$",
    r"исполним[аоы]\w*\s+без\s+(вас|тебя)",
    r"без\s+(вас|тебя)\s+исполним",
    r"ничего\s+(от\s+(вас|тебя)\s+)?не\s+ну[жд]",
    r"(от\s+(вас|тебя)\s+)?по-прежнему\s+ничего\s+не\s+ну[жд]",
    r"остаётся\s+(только\s+)?(взять|запустить|прогнать|дождаться)",
    r"осталось\s+(только\s+)?(взять|запустить|прогнать|дождаться)",
    r"готов[аоы]?\s+к\s+(исполнению|запуску|взятию)",
    r"исполнится\s+в\s+свой\s+чер[её]д",
    r"в\s+свой\s+чер[её]д\s*[.!]?\s*$",
]

COMPILED = [re.compile(p, re.IGNORECASE | re.MULTILINE) for p in HANDOFF_PATTERNS]

# Сколько последних символов ответа считать «закрывающей позицией».
# Тот же вопрос в середине разбора — законная часть рассуждения, не пауза.
TAIL_CHARS = 700


def extract_text(message):
    parts = []
    content = message.get("content", [])
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                parts.append(block.get("text", ""))
            elif isinstance(block, str):
                parts.append(block)
    return " ".join(parts)


def check(text):
    """Вернуть совпадение в хвосте ответа либо None. Выделено для тестируемости."""
    tail = text[-TAIL_CHARS:] if len(text) > TAIL_CHARS else text
    for pattern in COMPILED:
        match = pattern.search(tail)
        if match:
            return match.group().strip()
    return None


# ---------------------------------------------------------------------------
# Второй слой: судья вместо перечня
# ---------------------------------------------------------------------------
# Перечень выше ловит поверхностный ПРИЗНАК вместо предмета. Предмет —
# «передан ли ход»; признак — конкретные слова. Соответствия между ними нет:
# одно слово бывает передачей и отчётом («ждёт вашего слова» против «ждёт
# завершения тестов»), а одна передача — любыми словами.
#
# Это §28, применённая к себе: возведение признака в правило есть подмена
# сути прокси, и правило промахивается, когда признак не совпал с оракулом.
# Хук был написан против погони за грамматикой — и сам ею занимался: три
# наращивания перечня подряд, и на выдуманных за минуту формах 11 промахов
# из 13 («дальше — как решите», «не берусь решать за вас», «тут я
# останавливаюсь и передаю вам»).
#
# Метапозиция: спрашивать не «есть ли эти слова», а модель — «последний
# абзац передаёт ход человеку или отчитывается о сделанном». Образец взят
# у `post_write_memory_gate`: свежий `claude -p` из нейтрального каталога,
# проверка наличия двоичного файла, таймаут, fail-open на любой сбой.
#
# ЦЕНА, названная прямо: вердикт судьи не воспроизводится в точности, и
# батарея §24 для этого слоя перестаёт быть оракулом — она остаётся
# оракулом только для перечня. Поэтому перечень НЕ выброшен: он держит
# детерминированную часть и отвечает мгновенно, судья добирает остальное.

# 8 секунд — потолок паузы в конце ответа. Замер 2026-09-02: вызовы шли
# 6–19с, то есть часть вердиктов теряется по таймауту. Это осознанный
# размен: пауза дольше восьми секунд на КАЖДОМ ответе заметнее, чем
# редкий пропуск, — тем более что перечень остаётся и ловит очевидное
# мгновенно. Не успел — молчим (fail-open), оператор видит текст сам.
JUDGE_TIMEOUT_S = 8

JUDGE_PROMPT = """Ниже — последний абзац ответа ассистента оператору.

Ответь, ПЕРЕДАЁТ ЛИ он ход человеку, то есть работа остановлена и следующий
шаг за человеком, — или это ОТЧЁТ о сделанном, после которого ассистент
продолжает сам.

Передача хода: вопрос оператору, просьба подтвердить, объявление, что
дальше решает он, ожидание его слова, остановка до ответа. Формулировка
роли не играет — важно, кончилась ли работа на его слове.

Отчёт: рассказ о выполненном, предъявленный факт, названное ограничение,
описание состояния. Упоминание человека («выбранный вами», «вы просили»)
отчётом быть не перестаёт.

Сомневаешься — отвечай "report": ложная тревога дороже пропуска, оператор
и так видит текст.

Верни ТОЛЬКО JSON: {{"verdict": "handoff"|"report", "why": "<до 10 слов>"}}

Абзац:
---
{tail}
---"""

# Структурный предфильтр — БЕЗ перечня тем. Судью зовём, когда в хвосте нет
# следов совершённого действия: ни глаголов прошедшего времени, ни
# предъявленного факта (хеш, счёт, номер задачи). Отчёт почти всегда несёт
# хотя бы одно; передача хода — почти никогда.
#
# Сознательно НЕ ищем «вас/ваш/решение»: замер 2026-09-02 показал, что в
# обычном отчёте они встречаются постоянно (обращаюсь к оператору по делу),
# и такой предфильтр поднимал половину отчётов. А лексический предфильтр
# «признаки нерешённого» промахнулся на «готов продолжить по вашему
# сигналу» — то есть был тем же перечнем под другим именем.
_PAST_VERB = re.compile(r"\b\w+(ил|ал|ёл|ел|ул|ла|ло|ли)\b")
# Предъявленный факт: хеш коммита, счёт «N из M», номер задачи любого
# трекера. Номер намеренно родовой (БУКВЫ-ЦИФРЫ), а не наш префикс:
# у получателя трекер другой, и зашитое имя очереди было бы
# tenant-привязкой в общем коде.
_EVIDENCE = re.compile(r"\b[0-9a-f]{7,}\b|\b\d+\s*(из|/)\s*\d+\b"
                      r"|\b[A-Z][A-Z0-9]{1,9}-\d+\b")


def needs_judge(tail):
    """Хвост без следов сделанного — поднять к судье."""
    if _EVIDENCE.search(tail):
        return False
    return len(_PAST_VERB.findall(tail)) < 2


def ask_judge(tail):
    """Вердикт судьи: True — передача хода. Любой сбой → None (fail-open).

    Отдельный двоичный файл есть не везде (в среде Codex его нет вовсе),
    поэтому отсутствие — штатная ветка, а не ошибка: молча работает
    перечень, он самодостаточен.
    """
    judge_bin = os.environ.get("IVAN_HANDOFF_JUDGE", "claude")
    if shutil.which(judge_bin) is None:
        return None
    try:
        proc = subprocess.run(
            [judge_bin, "-p", JUDGE_PROMPT.format(tail=tail[:2000]),
             "--output-format", "json"],
            cwd="/tmp", capture_output=True, text=True, timeout=JUDGE_TIMEOUT_S,
        )
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return None
    if proc.returncode != 0:
        return None
    try:
        env = json.loads(proc.stdout)
        text = env.get("result", "") if isinstance(env, dict) else str(env)
    except (json.JSONDecodeError, ValueError):
        text = proc.stdout
    m = re.search(r'"verdict"\s*:\s*"(handoff|report)"', text)
    if not m:
        return None
    return m.group(1) == "handoff"


def main():
    try:
        hook_input = json.loads(sys.stdin.read())
    except (json.JSONDecodeError, ValueError):
        print(json.dumps({"decision": "allow"}))
        return

    transcript = load_messages(hook_input)
    if not transcript:
        print(json.dumps({"decision": "allow"}))
        return

    last = transcript[-1]
    if last.get("role") != "assistant":
        print(json.dumps({"decision": "allow"}))
        return

    text = extract_text(last)
    hit = check(text)
    if not hit:
        # Перечень промолчал — это ещё не «отчёт». Спрашиваем судью, если в
        # хвосте нет следов сделанного. Судья недоступен либо не уверен →
        # молчим: fail-open, оператор видит текст сам.
        tail = text[-TAIL_CHARS:] if len(text) > TAIL_CHARS else text
        if not tail.strip() or not needs_judge(tail):
            print(json.dumps({"decision": "allow"}))
            return
        if ask_judge(tail) is not True:
            print(json.dumps({"decision": "allow"}))
            return
        hit = "передача хода (по существу, не по формулировке)"

    print(json.dumps({
        "decision": "allow",
        "systemMessage": (
            f"Ход закрыт передачей развилки: «{hit}». "
            f"Прежде чем отдавать человеку, проверь: "
            f"(0) что здесь вычислимо, а что правда требует его слова; "
            f"(1) основание есть в файлах, правилах или фактах? → решай сам; "
            f"(2) след уходит наружу необратимо? нет → делай сам "
            f"с decision-record. Законный `in` (авторство нормы, приоритет, "
            f"замысел, публикация наружу) — оставь вопрос и назови, почему `in`."
        )
    }))


if __name__ == "__main__":
    import _host_adapter
    sys.exit(_host_adapter.run_main(main))
